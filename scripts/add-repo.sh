#!/usr/bin/env bash
# Put any GitHub repository under the Factory with one command (run as root):
#   scripts/add-repo.sh OWNER/REPO [INSTANCE]
# Creates the instance state on the shared data root, clones the repository,
# writes a generic instance profile and starts the instance and its watchdog.
# The repository needs no Factory files; its required GitHub CI is the merge gate.
set -euo pipefail

REPOSITORY=${1:-}
INSTANCE=${2:-}
FACTORY_USER=${FACTORY_USER:-dev}
STATE_ROOT=/var/lib/repo-factory
LOG_ROOT=/var/log/repo-factory
CONFIG_ROOT=/etc/repo-factory
CONTROL=$STATE_ROOT/control

if [[ ! "$REPOSITORY" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
  echo 'Usage: add-repo.sh OWNER/REPO [INSTANCE]' >&2
  exit 2
fi
if [ -z "$INSTANCE" ]; then
  INSTANCE=$(printf '%s' "${REPOSITORY#*/}" | tr '[:upper:]_.' '[:lower:]--')
fi
if [[ ! "$INSTANCE" =~ ^[a-z0-9][a-z0-9-]{0,40}$ ]]; then
  echo "Instance name must be lowercase letters, digits and hyphens: $INSTANCE" >&2
  exit 2
fi
if [ "$(id -u)" -ne 0 ]; then
  echo 'Run as root.' >&2
  exit 1
fi
profile="$CONFIG_ROOT/instances/$INSTANCE.env"
if [ -e "$profile" ]; then
  echo "Instance already exists: $profile" >&2
  exit 1
fi

base="$STATE_ROOT/$INSTANCE"
install -d -m 0750 -o "$FACTORY_USER" -g "$FACTORY_USER" \
  "$base" "$base/state" "$base/profiles" "$base/worktrees" "$base/recovery" \
  "$LOG_ROOT/$INSTANCE"
if [ ! -d "$base/repository/.git" ]; then
  runuser -u "$FACTORY_USER" -- git clone --quiet \
    "https://github.com/$REPOSITORY.git" "$base/repository"
fi
branch=$(runuser -u "$FACTORY_USER" -- git -C "$base/repository" symbolic-ref --short HEAD)

temporary=$(mktemp "$CONFIG_ROOT/instances/.$INSTANCE.XXXXXX")
cat > "$temporary" <<PROFILE
# Generated by add-repo.sh for $REPOSITORY. No human input: no ready label or
# author gate; restrict who may open issues in the repository's GitHub settings.
FACTORY_REPOSITORY=$base/repository
FACTORY_BASE_BRANCH=$branch
FACTORY_STATE_DIR=$base/state
FACTORY_LOG_DIR=$LOG_ROOT/$INSTANCE
FACTORY_PROFILE_STORE=$base/profiles
FACTORY_WORKTREE_DIR=$base/worktrees
FACTORY_RECOVERY_DIR=$base/recovery
FACTORY_REPOSITORY_PROFILE=generic
FACTORY_PROMPT_DIR=$CONTROL/automation/prompts
FACTORY_SYSTEM_PROMPT_PATH=$CONTROL/automation/prompts/generic-system.md
FACTORY_PROVIDER_CAPACITY_DIR=$STATE_ROOT/shared
FACTORY_AGENTS_CONFIG=$CONFIG_ROOT/agents.json
FACTORY_ARCHITECTURE=openhands-agent-canvas-v1
FACTORY_TASK_IMAGE=localhost/repo-factory-worker:current
FACTORY_MAX_PARALLEL_JOBS=2
FACTORY_NEW_ISSUE_INTERVAL_SECONDS=3600
FACTORY_NEW_ISSUES_PER_INTERVAL=4
FACTORY_REQUIRE_TRUSTED_INTAKE=false
FACTORY_REQUIRE_READY_LABEL=false
FACTORY_REQUIRE_GREEN_MAIN_BETWEEN_MERGES=false
FACTORY_MERGE_REVIEW_POLICY=ci-gated
GITHUB_REPOSITORY=$REPOSITORY
PROFILE
chown root:root "$temporary"
chmod 0644 "$temporary"
mv -T "$temporary" "$profile"

# Only collaborators may open issues the Factory will act on.
runuser -u "$FACTORY_USER" -- gh api -X PUT "repos/$REPOSITORY/interaction-limits" \
  -f limit=collaborators_only -f expiry=six_months >/dev/null || \
  echo 'WARNING: could not set interaction limits; restrict issue creation manually.' >&2

systemctl daemon-reload
systemctl enable --now "repo-factory@$INSTANCE.service" "repo-factory-health@$INSTANCE.timer"
echo "Factory instance $INSTANCE is running for $REPOSITORY ($profile)."
